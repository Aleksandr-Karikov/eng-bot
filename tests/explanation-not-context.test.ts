import { describe, expect, it } from "vitest";
import { buildPrompt, buildExtractPrompt } from "../src/llm/enricher";

/**
 * Баг #21: «слово tug при состоянии предложения постоянно требует, чтобы я использовал его
 * в переносном значении».
 *
 * `tug` многозначное: прямое «тянуть, дёргать» и идиома `tug at your heartstrings`. Человек встретил
 * слово в реплике про heartstrings, и объяснение сохранилось как «В данном контексте 'tug at your
 * heartstrings' означает…». На карточке рядом стояли три прямых значения в переводе и объяснение
 * про переносное — и выходило, будто слово значит только это.
 *
 * Реплика и так показывается отдельной строкой «Где встретилось». Объяснение должно говорить о самом
 * слове, а контекст — ограничивать перевод, а не подменять смысл.
 *
 * Проверка живой моделью (среда = прод): судья оба прямых употребления засчитывал —
 * «She tugged the rope hard» и «The child tugged at his mother's sleeve», — то есть дефект был
 * именно в объяснении, а не в проверке.
 */
describe("#21: объяснение говорит о слове, а не о реплике", () => {
  it("просит объяснять само слово, даже когда есть контекст", () => {
    const p = buildPrompt("tug", "тянуть, дёргать, тащить", "The dawn goose walk will tug at your heartstrings.");
    expect(p).toMatch(/объяснение самого слова/);
    expect(p).toMatch(/что оно значит вообще/);
    // И прямо запрещает формулу, из-за которой появился баг.
    expect(p).toMatch(/Не начинай explanation со слов «в данном контексте»/);
  });

  it("контекст ограничивает перевод, а не подменяет объяснение", () => {
    const p = buildPrompt("tug", "тянуть, дёргать, тащить", "The dawn goose walk will tug at your heartstrings.");
    expect(p).toContain("Перевод — в значении из этой реплики");
    // Прежняя формулировка велела объяснять «в значении из реплики» — отсюда и переносный смысл.
    expect(p).not.toMatch(/объясняй в значении из этой реплики/);
  });

  it("извлечение из текста просит то же самое", () => {
    const p = buildExtractPrompt("Some text here.");
    expect(p).toMatch(/что слово значит вообще/);
    expect(p).toMatch(/не «в данном контексте»/);
  });

  it("без контекста запрет не добавляется — там он не нужен", () => {
    const p = buildPrompt("bank", undefined, undefined);
    expect(p).toMatch(/объяснение самого слова/);
    expect(p).not.toMatch(/в данном контексте/);
  });
});
