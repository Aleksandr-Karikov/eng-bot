/**
 * Пульс бота: доказательство, что он не просто жив процессом, а реально работает.
 *
 * Зачем: 2 ноября 2026 процесс бота висел, логи не писались с 17:27, а Telegram не получал
 * `getUpdate s` — бот «умер» снаружи, оставаясь живым внутри. `pgrep` такое не ловит,
 * поэтому сторож смотрит на этот файл: если он давно не обновлялся, бот завис и его надо перезапустить.
 */
import { writeFileSync } from "node:fs";

/** Где пульс. Сторож (scripts/watchdog.ts) читает тот же путь. */
export const HEARTBEAT_FILE = "data/heartbeat";

/**
 * Пишем файл на каждый апдейт и на каждый успешный вызов Telegram API. Чаще раза в секунду не нужно:
 * время всё равно сравнивается с точностью до минут, а диск не должен работать вхолостую.
 */
export function touchHeartbeat(file = HEARTBEAT_FILE, now = new Date()): void {
  try {
    writeFileSync(file, String(now.getTime()));
  } catch {
    // Пульс — диагностика, а не работа: если диск недоступен, бот не должен из-за этого падать.
  }
}
