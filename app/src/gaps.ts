/**
 * Пропуски в предложении — для задания «вставь по смыслу» с несколькими пропусками (баг #25).
 *
 * Пропуск — три и больше подчёркиваний подряд: модель пишет и `___`, и `_______`. Частей текста
 * всегда на одну больше, чем пропусков, — по ним и рисуются поля ввода.
 */
const GAP = /_{3,}/g;

export const gapCount = (sentence: string): number => (sentence.match(GAP) ?? []).length;

/** Куски текста между пропусками: `a ___ b ___ c` → `["a ", " b ", " c"]`. */
export const gapSegments = (sentence: string): string[] => sentence.split(GAP);
